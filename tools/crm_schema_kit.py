_PROSE_STARTERS = {
    "просто", "проверить", "каждый", "каждая", "если", "когда", "это", "эта", "этот",
    "нет", "да", "все", "всё", "пусто", "нашлось", "статус", "закрываем", "пишем",
    "важное", "живой", "ход", "один", "больше", "формат", "главное", "через", "пакет",
    "чего", "как", "что", "для", "при", "без", "перед", "после",
}


def _is_cyrillic(tok):
    """Слово написано кириллицей — в любом регистре. Проверка только на заглавную была
    багом: «просто» с маленькой буквы прозой не считалось и шло в находки."""
    return bool(re.match(r"[А-Яа-яЁё]", tok))


def scan(text, names, common_words=None):
    """Список находок [(метка, фрагмент)]; пусто = чисто.

    `common_words` — основы, которые в ЭТОМ пакете встречаются во многих файлах: их гейт
    не считает именами, даже если такой человек в волте есть. Самокалибровка вместо
    ручного стоп-листа: имя живого человека редко, обычное слово — повсюду."""
    hits = []
    for rx, label in LEAK_PATTERNS:
        for m in rx.finditer(text):
            hits.append((label, m.group(0)[:60]))
    for m in RE_MAIL.finditer(text):
        if m.group(1).lower() not in ALLOWED_MAIL_DOMAINS:
            hits.append(("живая почта", m.group(0)[:60]))
    # Имена ищем ТОЛЬКО в написании с большой буквы: наш собственный текст — русская проза
    # и служебные поля в нижнем регистре, а просочившееся имя человека пишется с заглавной.
    # Без этого различителя гейт краснел на обычных словах, совпавших с частью имени файла.
    # Идём от ТЕКСТА к множеству имён, а не наоборот: имён в волте десятки тысяч, и прогон
    # «регулярка на каждое имя» занимал минуты вместо долей секунды.
    # Имена ищем по ВСЕМ словам, в любом регистре: «dziatkovskii» в слаге или ссылке —
    # такая же утечка, как «Dziatkovskii» в прозе (панель скептиков 24.09). Прощаем только
    # короткий список слов русской прозы, и только когда слово реально начинает фразу.
    for m in RE_WORD.finditer(text):
        tok = m.group(0)
        low = tok.lower()
        if stem(tok) not in names:
            continue
        if low in _PROSE_STARTERS and _is_cyrillic(tok):
            continue
        if common_words and stem(tok) in common_words:
            continue
        hits.append(("имя реального человека из волта", tok))
    return hits


def _w(path, text):
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text.rstrip() + "\n")


def build(out):
    """Собирает пакет. Возвращает (сколько демо-карточек, сколько лишних удалено)."""
    leads = os.path.join(out, "leads")
    os.makedirs(leads, exist_ok=True)

    _w(os.path.join(out, "README.md"), """# CRM тир 0 — формат без следов

Это НЕ наша база людей. Это её **форма**: какие поля несёт карточка, как устроена воронка,
по каким правилам её двигают, и дюжина выдуманных лидов, чтобы было видно, как это выглядит
в работе. Все имена в `leads/` заведомо ненастоящие (Example / Sample / Demo / Mock), почта
только на `example.com`. Реальных людей, контактов, переписок и сумм здесь нет.

| Файл | Что внутри |
|---|---|
| `SCHEMA.md` | поля карточки лида и какие из них обязательны |
| `FUNNEL.md` | стадии воронки и что означает переход |
| `RULES.md` | правила работы: темп, каналы, что нельзя |
| `lead_template.md` | пустая карточка — копируй и заполняй |
| `leads/` | 12 демонстрационных карточек |

## Как этим пользоваться
1. Прочитай `SCHEMA.md` — главное там: карточка несёт **весь контекст знакомства**, а не имя с фамилией.
2. Заведи свою папку `leads/` и клади туда по файлу на человека.
3. Когда людей станет больше пары десятков — переходи с файлов на базу; формат полей остаётся тот же.

## Граница
Пакет собран генератором и проверен гейтом: ноль живых имён, почт, хендлов, телефонов, сумм и путей.
Проверить самому: `python3 crm_schema_kit.py --verify <эта папка>` (exit 0 = чисто).
""")

    rows = "\n".join("| `%s` | %s | %s |" % (k, req, d) for k, req, d in FIELDS)
    _w(os.path.join(out, "SCHEMA.md"), """# Схема карточки лида

Главное правило: **карточка несёт весь контекст знакомства**, а не имя с фамилией. Через полгода
никто не вспомнит, почему этот человек здесь — значит, причина должна лежать в файле.

| Поле | Обязательно | Что значит |
|---|---|---|
%s

## Чего в карточке не бывает
- Выдуманных фактов. Не знаешь — оставь пусто или пометь «не подтверждено».
- Догадок в виде фактов: «наверное, он решает бюджет» — это гипотеза, так и пиши.
- Чужих секретов и приватного, что человек рассказал не для записи.

## Формат файла
Шапка с полями выше + текст свободной формы под ней: история знакомства, конспекты звонков,
что обещали и когда. Один человек = один файл.
""" % rows)

    frows = "\n".join("| `%s` | %s | %s |" % (k, ru, d) for k, ru, d in STAGES)
    _w(os.path.join(out, "FUNNEL.md"), """# Воронка

| Статус | По-русски | Когда ставится |
|---|---|---|
%s

## Правила перехода
- Статус двигает **факт**, а не надежда: «ответил» ставится, когда человек ответил, а не когда мы написали.
- У каждой карточки всегда есть `next_step` и понятно, **за кем ход**. Нет следующего шага — карточка мёртвая.
- Закрываем в `lost` только с **названной причиной**. Фраза «не пошло» причиной не является.
- `parked` обязан нести дату возврата, иначе это тот же `lost`, только тихий.
""" % frows)

    _w(os.path.join(out, "RULES.md"), """# Правила работы с людьми

## Темп
- Живой диалог важнее холодного: сперва отвечаем тем, кто написал нам, потом идём к новым.
- Ход за нами и висит больше трёх дней — это долг, а не «пока подождём».
- Ход за ними и тишина — можно напомнить один раз. Второе напоминание без новой пользы не шлём.

## Каналы
- Пишем туда, где человек нам **отвечал**, а не туда, где больше наших сообщений.
- Важное дублируем во все уже открытые с ним двери. Открытая дверь — та, где переписка уже была;
  найти однофамильца в поиске и написать ему — это не дубль, а холодное касание.

## Чего не делаем
- Одинаковый текст веером разным людям. Одно точное сообщение в правильную дверь — это громкость;
  один текст всем — это спам.
- Не выдумываем цифры и факты о себе. Приукрасить рамку можно, соврать в числах — нет.
- Не пишем от чужого имени и не отрицаем, что собеседник говорит с роботом, если он прямо спросил.

## Когда файлов становится мало
Больше ~20 живых диалогов или задача повторяется — заводится движок: база, журнал касаний,
дневной лимит отправки. Формат полей при этом не меняется, меняется только хранилище.
""")

    tmpl = ["---"]
    for k, req, d in FIELDS:
        tmpl.append('%s: ""   # %s%s' % (k, d, "" if req == "да" else " (необязательно)"))
    tmpl += ["---", "", "# <имя>", "", "## История знакомства", "- <дата> — что произошло",
             "", "## Что обещали", "- <что, кому, к какому числу>"]
    _w(os.path.join(out, "lead_template.md"), "\n".join(tmpl))

    keep = set()
    for (slug, name, org, role, entered, source, met, why, useful, indirect,
         status, touch, nxt, channels, tags) in DEMO:
        keep.add(slug + ".md")
        card = """---
name: "%s"
org: "%s"
role: "%s"
entered_on: %s
source: "%s"
met_where: "%s"
why: "%s"
useful_for: "%s"
indirect: "%s"
status: %s
last_touch: %s
next_step: "%s"
channels: [%s]
tags: [%s]
---

# %s

- **Кто:** %s, %s
- **Занесён:** %s, источник — %s
- **Где пересеклись:** %s
- **Почему занёс:** %s
- **Чем полезен:** %s
- **Косвенные связи:** %s
- **Стадия:** %s, последнее касание %s
- **Следующий шаг:** %s

## История знакомства
- %s — первое касание: %s
""" % (name, org, role, entered, source, met, why, useful, indirect, status, touch, nxt,
            ", ".join('"%s"' % c for c in channels), ", ".join(tags),
            name, org, role, entered, source, met, why, useful, indirect, status, touch, nxt,
            entered, met)
        _w(os.path.join(leads, slug + ".md"), card)

    # Подчищаем ТОЛЬКО свои же демо-карточки из прошлых версий, а не всё подряд: после
    # передачи человеку в leads/ лежат ЕГО карточки, и «пересобери CRM» не должна стирать
    # его работу (панель скептиков 24.09 — документированная команда стирала карточки
    # получателя и рапортовала успех).
    ours = {slug + ".md" for slug, *_ in DEMO} | {n + ".md" for n in
                                                  ("alice", "bob", "carol", "dave", "erin")}
    removed = 0
    for path in glob.glob(os.path.join(leads, "*.md")):
        base = os.path.basename(path)
        if base not in keep and base in ours:
            os.remove(path)
            removed += 1
    return len(DEMO), removed


def verify(out, strict_names=True):
    """Находки по всему пакету: [(файл, метка, фрагмент)]. Пусто = отдавать можно.

    Смотрит КАЖДЫЙ файл, а не только `*.md`: первая версия читала лишь markdown, и
    подложенные .csv, .json, .env и файл с заглавным .MD проходили насквозь. Незнакомое
    расширение и точечный файл — сами по себе находки, а не повод пропустить. Имя файла
    проверяется наравне с содержимым: карточка `anton-dziatkovskii.md` с нейтральным
    текстом внутри — утечка ровно такая же.
    """
    names = live_names()
    bad = []
    if not os.path.isdir(out):
        return [("<путь>", "каталога не существует — проверять нечего", out)]
    # ⚠️ Прибор — тоже claim. Список имён пуст (волта нет, путь другой, каталог переименован)
    # означает, что проверка по людям НЕ ВЫПОЛНЯЛАСЬ; печатать при этом зелёное — худший из
    # возможных ответов. Панель скептиков показала это живьём: с подменённым HOME пакет с
    # тремя настоящими именами получал «✅ чисто» и exit 0.
    blind = len(names) < 100
    if blind and strict_names:
        # У НАС это стоп: гейт перед выдачей обязан видеть людей, иначе он подтверждает
        # сам себя. У ПОЛУЧАТЕЛЯ волта нет по определению — там та же слепота ожидаема,
        # и она печатается словами, но не роняет проверку (иначе инструмент бесполезен).
        bad.append(("<прибор>", "проверка по именам НЕ выполнялась: волт не найден (%s), "
                                "имён в списке %d" % (PEOPLE_DIR, len(names)), ""))
    files_all = []
    for root, dirs, files in os.walk(out):
        for f in sorted(files):
            files_all.append(os.path.join(root, f))
    if not files_all:
        return [("<путь>", "каталог пуст — проверять нечего", out)]

    # Первый проход: как часто слово встречается в РАЗНЫХ файлах пакета. Имя живого
    # человека редко, обычное слово («надежда», «журнал», «founder») — повсюду. Так гейт
    # сам калибрует свой шум, вместо ручного стоп-листа, который всегда отстаёт.
    doc_freq = {}
    texts = {}
    for path in files_all:
        rel = os.path.relpath(path, out)
        try:
            with io.open(path, encoding="utf-8", errors="ignore") as fh:
                texts[rel] = fh.read()
        except OSError:
            texts[rel] = ""
        for st in {stem(t) for t in RE_WORD.findall(texts[rel])}:
            doc_freq[st] = doc_freq.get(st, 0) + 1
    threshold = max(2, len(files_all) // 6)
    common = {w for w, c in doc_freq.items() if c > threshold}

    for path in files_all:
        rel = os.path.relpath(path, out)
        f = os.path.basename(path)
        if not f.lower().endswith(".md") or f.startswith("."):
            bad.append((rel, "файл не из пакета (чужой тип или точечный)", f))
            continue
        for label, frag in scan(rel.replace(os.sep, " "), names, common):
            bad.append((rel, label + " — в ИМЕНИ файла", frag))
        for label, frag in scan(texts[rel], names, common):
            bad.append((rel, label, frag))
    return bad


def main():
    ap = argparse.ArgumentParser(
        description="CRM тир 0: схема + воронка + правила + демо-лиды, ноль наших следов")
    ap.add_argument("--out", help="куда собрать пакет")
    ap.add_argument("--verify", help="проверить собранный пакет (exit 1 = нашлось живое)")
    ap.add_argument("--strict-names", action="store_true",
                    help="требовать, чтобы база людей была доступна (наш гейт перед выдачей)")
    a = ap.parse_args()
    if a.out:
        out = os.path.abspath(os.path.expanduser(a.out))
        n, removed = build(out)
        print("✅ собран CRM тир 0: %s (демо-карточек %d, лишних удалено %d)" % (out, n, removed))
        # Сборка на машине ПОЛУЧАТЕЛЯ не обязана видеть нашу базу людей: там её нет и не
        # будет. Строгий режим — это наш гейт перед выдачей (--strict-names).
        bad = verify(out, strict_names=a.strict_names)
        if bad:
            for rel, label, frag in bad[:20]:
                print("🔴 %-22s %-34s %s" % (rel, label, frag))
            raise SystemExit("🔴 BLOCKED: в пакет просочилось живое — наружу не отдавать.")
        print("   гейт: живых имён, почт, хендлов, телефонов, сумм, путей — 0")
        return
    if a.verify:
        target = os.path.abspath(os.path.expanduser(a.verify))
        if len(live_names()) < 100:
            print("ℹ️ базы людей на этой машине нет — проверка по именам пропущена, "
                  "остальные проверки работают")
        bad = verify(target, strict_names=a.strict_names)
        if bad:
            for rel, label, frag in bad[:40]:
                print("🔴 %-22s %-34s %s" % (rel, label, frag))
            raise SystemExit(1)
        print("✅ пакет чист: живых имён, почт, хендлов, телефонов, сумм, путей — 0")
        return
    ap.print_help()


if __name__ == "__main__":
    main()
