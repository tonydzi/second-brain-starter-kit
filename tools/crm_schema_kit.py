def stem(tok):
    """Грубая основа слова. Нужна, потому что русский склоняет имена: «Кирилл», «Кириллом»
    и «Кириллу» — три разных токена, и точное сравнение пропускало два из трёх (панель
    скептиков, второй заход 24.09: «Звонок Кирилла перенесли» проходил как чистый)."""
    low = tok.lower()
    if not re.match(r"[а-яё]", low):
        return low
    for end in _CASE_ENDINGS:
        if len(low) - len(end) >= 4 and low.endswith(end):
            return low[:-len(end)]
    return low


_PROSE_CACHE = {}


def prose_stems(corpus_dir=None, min_files=20):
    """Основы ОБЫЧНЫХ слов, посчитанные по большому корпусу нашего же текста (Библия правил).

    Зачем: в волте 19 тысяч карточек людей, и среди их имён неизбежно попадаются слова
    языка — «Надежда», «Вера», «[человек]». Ручной стоп-лист такие совпадения не догонит.
    Корпус метода людей почти не содержит, поэтому слово, встречающееся в нём в МНОГИХ
    файлах, — это слово языка, а не имя. Порог высокий (20 файлов) осознанно: имя живого
    лида всё же мелькает в наших скиллах — «jiten» нашёлся в 6 файлах и при пороге 3 тихо
    становился «обычным словом», то есть переставал ловиться. Настоящие слова языка стоят
    в десятках файлов: «врем» 69, «секрет» 112, «команд» 130. Считается раз за прогон.
    """
    dirs = corpus_dir or [
        os.path.join(os.path.expanduser("~/Obsidian/PaloAlto-AI-Research-Lab-Knowledge"),
                     "05-Protocols-Bible"),
        os.path.expanduser("~/.claude/skills"),
    ]
    if isinstance(dirs, str):
        dirs = [dirs]
    key = "|".join(dirs)
    if key in _PROSE_CACHE:
        return _PROSE_CACHE[key]
    freq = {}
    files = []
    for d in dirs:
        files += glob.glob(os.path.join(d, "**", "*.md"), recursive=True)
    for path in files:
        try:
            with io.open(path, encoding="utf-8", errors="ignore") as f:
                text = f.read()
        except OSError:
            continue
        for st in {stem(t) for t in RE_WORD.findall(text)}:
            freq[st] = freq.get(st, 0) + 1
    out = {w for w, c in freq.items() if c >= min_files}
    _PROSE_CACHE[key] = out
    return out


def live_names(people_dir=PEOPLE_DIR):
    """Основы имён реальных людей из волта.

    Берём и ИМЯ ФАЙЛА карточки, и поля `title:`/`aliases:` внутри неё — в волте принят
    слаг вида `person-jiten-oswal-2.md`, а человеческое имя живёт во frontmatter. Прежняя
    версия требовала «два слова с заглавной и без цифр» и знала лишь **37%** людей: живой
    инвестор-лид проезжал мимо гейта с зелёным вердиктом (панель, второй заход 24.09).

    Ложные срабатывания гасим не здесь, а на месте проверки: слово, которое встречается
    во МНОГИХ файлах пакета, — обычное слово, а не имя (см. `verify`).
    """
    skip = demo_vocab() | COMMON_WORDS | prose_stems()
    names = set()
    for path in glob.glob(os.path.join(people_dir, "**", "*.md"), recursive=True):
        rel = os.path.relpath(path, people_dir)
        if rel.split(os.sep)[0].lower() in ("_moc", "moc", "archive"):
            continue
        base = os.path.splitext(os.path.basename(path))[0]
        if base.startswith("_") or base.lower().startswith(("cv-", "moc-", "list-")):
            continue
        # Только КАРТОЧКИ ЛЮДЕЙ: в 07-People лежат ещё импорты, дампы и списки, и их
        # заголовки несут слова языка. Замер 24.09: без этого фильтра список имён 35 796
        # токенов и в нём «время», «рассылка», «lost»; с фильтром — 16 443 и чисто.
        if not base.startswith("person-"):
            try:
                with io.open(path, encoding="utf-8", errors="ignore") as f:
                    if "relationship:" not in f.read(400):
                        continue
            except OSError:
                continue
        raw = [base]
        try:
            with io.open(path, encoding="utf-8", errors="ignore") as f:
                head = f.read(400)
            # Берём ИМЕННО поля имени. `aliases` в волте несёт свободный текст вроде
            # «Jiten VC Angel Bay Area», и от него список разбухал до 45 тысяч «имён»,
            # среди которых «время» и «рассылку» — гейт начинал краснеть на прозе.
            for m in re.finditer(r"^(?:title|name)\s*:\s*[\"']?([^\"'\n]+)", head, re.M):
                raw.append(m.group(1))
        except OSError:
            pass
        for chunk in raw:
            chunk = re.sub(r"^person-", "", chunk.strip())
            chunk = re.sub(r"-\d+$", "", chunk)
            parts = [p for p in re.split(r"[^A-Za-zА-Яа-яЁё]+", chunk) if len(p) >= 4]
            if len(parts) > 5:
                continue  # это описание, а не имя человека
            for part in parts:
                # Сравниваем ОСНОВУ с основой: стоп-листы хранят основы, и проверка сырого
                # слова пропускала «Время» мимо «врем» — гейт потом краснел на своей прозе.
                if stem(part) not in skip:
                    names.add(stem(part))
    return names


