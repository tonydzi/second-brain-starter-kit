# ⚠️ КОРОТКАЯ ЧАСТЬ — ТОЛЬКО ТОЧНЫМ СЛОВОМ, И ЭТО ПЕРЕМЕРЕНО (06.10.2026).
# Панель ломателей (codex+grok, независимо) назвала правило дырой: у ключа `прибор вр` часть
# `вр` короткая, значит окно ему выключено, и «прибор сейчас врёт о свежести выхода» мимо
# семьи. Дыра РЕАЛЬНА (воспроизведена), но лечить её ослаблением правила — хуже болезни:
# замер показал, что префикс в ДВА символа ловит «временно · вручную · вроде · времени», и
# семья получила +32 строки с точностью ~65% (20 из них по одному этому ключу: «параллельные
# сессии пишут вслепую», «тесты пишут в боевой лог», «РАСПИСКА засчитана как ход» — чужие
# корни). Правильная заплатка — честный КЛЮЧ, а не общий матчер: ниже в семью добавлены
# `прибор врёт/врал/врут` с частями >=4 символов, и окно работает на них штатно.
# Раздутый счёт — такая же ложь, как заниженный; ответ панели: дыру закрыли, но её лечением.
def _part_in(part, words):
    if len(part) <= 3:
        return part in words                      # короткое — только точным словом
    return any(w.startswith(part) for w in words)  # длинное — префиксом, хвосты склонений


def _near(parts, words, gap=None):
    """Части ключа идут В ТОМ ЖЕ ПОРЯДКЕ, между соседними <= gap слов (по умолч. FAM_WINDOW).

    Порядок обязателен (замер 05.10.2026): без него «пусто из одного места = вердикт
    "нет на диске"» совпадало с ключом «на диске пусто» — слова те же, дефект другой.
    Пропуск слов между частями разрешён — ровно он и нужен: «сторож КРАСИТ зелёным».
    """
    n = len(words)
    gap = FAM_WINDOW if gap is None else gap
    if _ordered(parts, words, gap):
        return True
    # ОБРАТНЫЙ ПОРЯДОК РАЗРЕШЁН, НО ВПЛОТНУЮ (ревизия 06.10.2026 по панели ломателей, обе
    # рельсы): «зелёный сторож» и «зелёным красится сторож» — тот же дефект, что «сторож
    # зелён», и прямой порядок их не брал. Зазор 2, а не 6: русская инверсия держит слова
    # рядом, а именно ДАЛЬНИЙ разброс и давал ложняк, из-за которого порядок вводился
    # («пусто из одного места = вердикт нет на диске» против ключа «на диске пусто»).
    if gap > 2 and len(parts) == 2:
        return _ordered(list(reversed(parts)), words, 2)
    return False


def _ordered(parts, words, gap):
    n = len(words)
    for i, w in enumerate(words):
        if not _part_in(parts[0], (w,)):
            continue
        pos, ok = i, True
        for pt in parts[1:]:
            nxt = None
            for j in range(pos + 1, min(n, pos + 1 + gap)):
                if _part_in(pt, (words[j],)):
                    nxt = j
                    break
            if nxt is None:
                ok = False
                break
            pos = nxt
        if ok:
            return True
    return False


def _slug_parts(key):
    """Части ДЕФИСНОГО ключа без пробелов (`silent-green`) — кэш, иначе None.

    Зачем (root-fix 05.10.2026): `selfheal._warn_if_family_is_older` строит запрос как
    `slug.replace("-", " ")`, после чего дефисный ключ слеп к СВОЕМУ ЖЕ классу --
    `silent-green-watchdog` не доходил до семьи instrument-vrjot-zelyonym, где ключ
    `silent-green` стоит дословно. Отсюда живая улика той же ночи: сессия завела класс
    `exit-code-of-pipe-not-of-script`, и дверь ответила «НОВЫЙ класс», сбросив счёт с 3 на 1.
    Зазор 1 (строгое соседство): слаг пишется словами подряд, ширить тут нечего.
    """
    if key not in _SLUG_PARTS:
        parts = None
        if " " not in key and ("-" in key or "_" in key):
            got = [w for w in _WORD.findall(key.lower()) if w]
            parts = got if len(got) > 1 else None
        _SLUG_PARTS[key] = parts
    return _SLUG_PARTS[key]


def _key_hits(key, low, words):
    if key in low:
        return True                 # дешёвый путь первым: прежние совпадения не теряем
    parts = _key_parts(key)
    if parts:
        if parts[0] in low and _near(parts, words):
            return True
    slug = _slug_parts(key)
    if slug and slug[0] in low:
        return _near(slug, words, gap=1)
    return False


def families_of(text, only=None):
    """Канон-имена семей, к которым относится текст. lower() юникод-корректен для
    кириллицы (в отличие от grep -i); фразовые ключи — окном слов, см. FAM_WINDOW.

    `only` — проверять ТОЛЬКО эти семьи. Нужно не для смысла, а для цены: сканер журнала
    сверяет каждую строку с семьями ЗАПРОСА (обычно 0-2), а не со всеми 18 (замер 06.10:
    5.9s -> 0.6s на 3960 строках; окно с порядком дороже прежней подстроки, и без этого
    отсечения прибор стал бы ждать минуты там, где его дёргают из /tt и /retro).
    """
    low = (text or "").lower()
    words = _WORD.findall(low)
    items = FAMILIES.items() if only is None else (
        (f, FAMILIES[f]) for f in only if f in FAMILIES)
    return {fam for fam, keys in items
            if any(_key_hits(k, low, words) for k in keys)}


def split_class_hits(query, path=None, min_hits=3, top=6):
    """Прежние случаи того же ДЕФЕКТА, РАЗДЕЛЁННЫЕ на два вида. -> (fam, words, n_lines).

    СЕМЕЙНЫЕ (fam): строка попала в ту же СЕМЬЮ дефекта, что и запрос. Только они идут
    в счёт §5.10 — семья и есть «тот же дефект под другим именем».
    СЛОВЕСНЫЕ (words): совпало >= min_hits разных слов и НИ ОДНОЙ семьи. Это подсказка
    для глаз, а не улика: §5.10 по ним не считается.

    ⚠️ ЗАЧЕМ РАЗДЕЛЕНО (замер 05.10.2026, воспроизведён двумя сессиями на хабе):
    запрос «тихий откат на медленный путь: прибор не называет, каким путём получен
    результат» печатал «ПРЕЖНИЕ СЛУЧАИ (6) — это НЕ 1-й случай» по обрывкам
    `путь · прибор · называ · резуль`, и в той же выдаче рядом с родственниками стояли
    переименование репо и врущий поиск в MB-конфигураторе. §5.10 принимает это число
    как РАЗРЕШЕНИЕ строить механизм, то есть прибор, заведённый против недостижимого
    порога, умел порог ПОДДЕЛЫВАТЬ. Ошибка дорога в обе стороны: заниженный счёт
    хоронит класс молча, завышенный тратит сессию на механизм под единственный случай.
    """
    q = token_set(query)
    qfam = families_of(query)
    path = path or journal_path()
    if not path or not os.path.isfile(path) or (not q and not qfam):
        return [], [], 0
    fam_hits, word_hits, n_lines = [], [], 0
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                s = line.strip()
                if len(s) < 40 or not CASE_LINE.search(s):
                    continue
                n_lines += 1
                shared = qfam & families_of(s, only=qfam) if qfam else set()
                matched = q & token_set(s)
                if not shared and len(matched) < min_hits:
                    continue
                date = CASE_LINE.search(s).group(0)
                score = len(matched) + 5 * len(shared)
                why = sorted(matched) + ["семья:" + f for f in sorted(shared)]
                (fam_hits if shared else word_hits).append((score, date, s, why))
    except Exception:
        return [], [], 0
    for rows in (fam_hits, word_hits):
        rows.sort(key=lambda x: (-x[0], x[1]))
    return fam_hits[:top], word_hits[:top], n_lines


def scan_class(query, path=None, min_hits=3, top=6):
    """СОВМЕСТИМОСТЬ: прежняя пара (hits, n_lines), семейные впереди словесных.
    Новый код берёт split_class_hits — иначе словесный шум не отличить от улики
    (так и жил `selfheal._warn_if_family_is_older`: печатал «у СЕМЬИ ещё N прежних
    случаев» про совпадения по обрывкам слов)."""
    fam, words, n_lines = split_class_hits(query, path, min_hits, top)
    return (fam + words)[:top], n_lines


def family_prior_count(query, path=None, min_hits=3, top=None):
    """Сколько прежних случаев ТОЙ ЖЕ СЕМЬИ — единственное число, которое имеет право
    попадать в счёт §5.10. Для потребителей вроде selfheal.

    ⚠️ СЧЁТ НЕ ОБРЕЗАЕТСЯ ПОТОЛКОМ ВЫДАЧИ (замер 06.10.2026, /five-whys по семье
    `vneshnyaya-zapis-o-registracii-protuhla`). Прежний дефолт `top=6` отдавал
    `len(fam_hits[:6])`, и дверь журнала печатала «у СЕМЬИ ещё 6 прежних случаев
    (итого 7, порог 3)» при СЕМНАДЦАТИ строках семьи в журнале. То есть число,
    которое §5.10 принимает как разрешение строить механизм, упиралось в потолок
    СПИСКА и переставало расти ровно там, где семья становится самой дорогой.
    Ошибка тихая в обе стороны: 7 вместо 17 занижает серию втрое, а на границе
    порога потолок умел бы и подделать «порог взят». Потолок остаётся у СПИСКА
    (`split_class_hits`, глазам хватает шести), у СЧЁТА потолка нет.
    """
    fam, _words, _n = split_class_hits(query, path, min_hits, top)
    return len(fam)


def scan_family(fam, path=None):
    """Сколько ВСЕГО случаев одной семьи в журнале и с какой даты идёт счёт."""
    path = path or journal_path()
    if not path or not os.path.isfile(path) or fam not in FAMILIES:
        return 0, None
    keys = FAMILIES[fam]
    n, first = 0, None
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            s = line.strip()
            if len(s) < 40 or not CASE_LINE.search(s):
                continue
            low = s.lower()
            words = _WORD.findall(low)
            if any(_key_hits(k, low, words) for k in keys):
                n += 1
                d = CASE_LINE.search(s).group(0)
                if first is None or d < first:
                    first = d
    return n, first


