# ⚠️ БЕЗ подчёркивания в классе символов: иначе tg_voice_router.py — ОДИН токен,
# и прибор слеп ровно к snake_case-именам, ради которых он и сделан (поймано тестом 03.09).
_WORD = re.compile(r"[0-9a-zA-Zа-яёА-ЯЁ]+", re.UNICODE)


def tokens(text):
    """Слова -> нормализованные основы. str.lower() юникод-корректен для кириллицы
    (в отличие от grep -i, который на кириллице молча промахивается)."""
    out = []
    for w in _WORD.findall(text or ""):
        w = w.lower()
        if len(w) < 4 or w.isdigit():
            continue
        stem = w[:6]               # дешёвый стемминг: хвосты склонений отрезаны
        # СТОП-ПРОВЕРКА ИДЁТ И ПО ОСНОВЕ (01.10.2026). Раньше она шла только по ПОЛНОМУ
        # слову, а в множество попадала основа -- поэтому «наблюдался» проскакивал мимо
        # списка и становился основой «наблюд», которая в журнале стоит в 39% строк.
        # Склонять вручную каждую форму = проигранная гонка; сверяем обе формы.
        if w in STOP or stem in STOP:
            continue
        out.append(stem)
    return out


