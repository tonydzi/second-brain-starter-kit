HEAD_BYTES = 3000


def _read_head(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.read(HEAD_BYTES)
    except Exception:
        return ""


def scan_build(query, surfaces=None, min_hits=2):
    """Возвращает (hits, n_surfaces, n_files). hit = (score, surface, path, why)."""
    q = token_set(query)
    if not q:
        return [], 0, 0
    surfaces = surfaces if surfaces is not None else build_surfaces()
    hits, n_files, n_surf = [], 0, 0
    for name, root, exts, recursive in surfaces:
        if not os.path.isdir(root):
            continue
        n_surf += 1
        walker = os.walk(root) if recursive else [(root, [], os.listdir(root))]
        for dirpath, _dirs, files in walker:
            for fn in files:
                if not fn.lower().endswith(exts):
                    continue
                if fn.startswith("_test_") or ".bak" in fn:
                    continue
                # архивы Syncthing и корзины — не «готовое», а мусор в выдаче
                if ".stversions" in dirpath.lower() or ".stfolder" in dirpath.lower():
                    continue
                path = os.path.join(dirpath, fn)
                if not os.path.isfile(path):
                    continue
                n_files += 1
                name_hits = q & token_set(fn)
                body_hits = q & token_set(_read_head(path))
                # ЧИСЛО РАЗНЫХ совпавших слов важнее веса имени: иначе один общий
                # токен («telegram») выносит наверх десятки посторонних файлов и
                # хоронит настоящий готовый движок (замер 03.09, 190 находок).
                score = 10 * len(name_hits | body_hits) + 3 * len(name_hits)
                matched = name_hits | body_hits
                need = min_hits if len(q) > 1 else 1
                if name_hits or len(matched) >= need:
                    if len(matched) >= need or name_hits:
                        hits.append((score, name, path, sorted(matched)))
    hits.sort(key=lambda x: -x[0])
    return hits, n_surf, n_files


