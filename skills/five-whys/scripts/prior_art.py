def self_test():
    import tempfile
    ok = fail = 0

    def check(name, cond):
        nonlocal ok, fail
        if cond:
            ok += 1
        else:
            fail += 1
            print("  FAIL:", name)

    # 1. токенизация: кириллица приводится к нижнему регистру (грабли grep -i)
    check("кириллица lower", token_set("ГОЛОСОВЫЕ") == token_set("голосовые"))
    check("стоп-слова выброшены", "класса" not in " ".join(tokens("класса поломки")))
    check("короткие выброшены", tokens("и на до") == [])

    tmp = tempfile.mkdtemp(prefix="prior_art_")
    # 2. build: находит готовый файл по имени
    sub = os.path.join(tmp, "scripts")
    os.makedirs(sub)
    with open(os.path.join(sub, "tg_translate_3chats.py"), "w", encoding="utf-8") as f:
        f.write('"""перевод голосовых в три рабочих чата"""\n')
    with open(os.path.join(sub, "unrelated_backup.py"), "w", encoding="utf-8") as f:
        f.write('"""бэкап волта на диск"""\n')
    # имя говорит, тело молчит — так выглядел реальный промах 03.09
    with open(os.path.join(sub, "tg_voice_router.py"), "w", encoding="utf-8") as f:
        f.write('"""заглушка, тело ничего не сообщает"""\n')
    surf = [("scripts", sub, (".py",), False)]
    hits_name, _, _ = scan_build("voice router", surf)
    check("build: ловит по ОДНОМУ имени файла", any("tg_voice_router" in h[2] for h in hits_name))
    # ветка name_hits изолированно: из трёх слов запроса имя ловит ТОЛЬКО одно
    hits_one, _, _ = scan_build("router персональный ассистент", surf)
    check("build: одного слова В ИМЕНИ хватает", any("tg_voice_router" in h[2] for h in hits_one))
    hits, ns, nf = scan_build("telegram translate голосовых чата", surf)
    check("build: нашёл готовый движок", any("tg_translate_3chats" in h[2] for h in hits))
    check("build: не притащил чужое", not any("unrelated_backup" in h[2] for h in hits))
    check("build: счётчик файлов честный", nf == 3 and ns == 1)
    hits2, _, _ = scan_build("квантовая криптография эльфов", surf)
    check("build: на пустом запросе молчит", hits2 == [])

    # 3. class: находит прежний случай под ДРУГИМ именем
    jp = os.path.join(tmp, "j.md")
    with open(jp, "w", encoding="utf-8") as f:
        f.write("- 2026-08-20 · объявил отсутствие подкоманды, проверив ОДИН файл из двух поверхностей\n")
        f.write("- 2026-08-22 · вердикт рельса мертва вынесен по одному месту из девяти поверхностей\n")
        f.write("- 2026-07-01 · совершенно посторонняя запись про бэкап диска и ленту\n")
        f.write("длинная строка про один файл и поверхности, но БЕЗ даты — не случай\n")
        f.write("коротко\n")
    hits3, nl = scan_class("вывод по одному месту из многих поверхностей", jp)
    check("class: нашёл ОБА прежних под разными именами", len(hits3) >= 2)
    check("class: посторонняя запись не попала", not any("посторонняя" in h[2] for h in hits3))
    check("class: считает только строки-случаи", nl == 3)
    hits4, _ = scan_class("протухший сертификат домена регистратора", jp)
    check("class: чистый запрос даёт пусто", hits4 == [])
    # семья связывает то, что лексика не связывает — ядро починки
    check("семья опознана по запросу", "vyvod-po-odnoy-poverhnosti" in families_of("вынесен по одному месту"))
