# ⚠️ ТРИ ОГРАНИЧИТЕЛЯ ОКНА — замерены 05.10.2026 на живом журнале (3831 строка-случай),
# каждый поставлен по НАЙДЕННОМУ ложному совпадению, а не из осторожности:
