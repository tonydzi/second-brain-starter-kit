def selftest():
    ok = True
    for name, sample, want in (("ванильный", VANILLA_SAMPLE, 2), ("живой", LIVE_SAMPLE, 0)):
        _, _, worst, _ = scan(sample)
        good = worst == want
        ok &= good
        print("selftest %-10s -> worst=%d (ждали %d) %s" % (name, worst, want, "OK" if good else "СЛОМАНО"))
    print("SELFTEST", "OK" if ok else "FAILED")
    return 0 if ok else 2


def main():
    ap = argparse.ArgumentParser(description="маркеры ванильного/робот-голоса в авторском тексте Антона")
    ap.add_argument("path", nargs="?", help="файл .md/.txt, или - для stdin")
    ap.add_argument("--selftest", action="store_true", help="прогнать зашитые образцы")
    a = ap.parse_args()
    if a.selftest:
        sys.exit(selftest())
    if not a.path:
        ap.print_help(); sys.exit(3)
    if a.path == "-":
        raw = sys.stdin.read()
    else:
        if not os.path.exists(a.path):
            print("ERR нет такого файла: %s" % a.path); sys.exit(3)
        raw = io.open(a.path, encoding="utf-8", errors="replace").read()
    if not raw.strip():
        print("ERR пустой вход"); sys.exit(3)
    sys.exit(report(a.path, raw))


if __name__ == "__main__":
    main()
