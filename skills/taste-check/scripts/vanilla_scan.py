#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""
vanilla_scan.py - ПАСПОРТ ДЕТАЛИ (канон [[coverage-and-docs-every-part]], §5.8)

ЧТО ДЕЛАЕТ: детерминированно (0 токенов, 0 LLM) считает шесть маркеров «ванильного/
робот-голоса» в авторском тексте от лица Антона и печатает вердикт PASS/WARN/FAIL.
Это слой ВИДИМОСТИ для принципов P26-P30 скилла /taste-check: без прогона принцип
существует только на бумаге («проверка без прогона = нет проверки»).

ОТКУДА ЦИФРЫ: замер 2026-07-28 - 42 наших написанных черновика
([путь владельца] 25 240 слов)
против реальных текстов Антона: ★ЭТАЛОН 06.06 (его СОБСТВЕННАЯ правка) + 3 его FB-поста
из 04-Projects\personal\facebook-diary-auto\_STYLE.md + DM-корпус 3 273 реплики
(_originals\facebook-dm-voice-2017-2021\anton_voice_corpus_RU.txt). Частоты на 1000 слов.

ВХОД : путь к .md/.txt (или - для stdin). HTML-комментарии, frontmatter и URL вырезаются.
ВЫХОД: таблица «маркер | наш текст | норма Антона | вердикт» + строка ИТОГ + код возврата.
       exit 0 = PASS · 1 = WARN · 2 = FAIL · 3 = ошибка входа (файла нет / пусто).
КТО ДЁРГАЕТ: скилл /taste-check (шаг 3, детерминированные проверки) и любой писатель
       перед выдачей авторского черновика Антону.
ЧТО ЛОМАЕТСЯ: (а) файл не в UTF-8 -> читаем с errors=replace, не падаем; (б) текст короче
       120 слов (тизер) -> частоты шумят, печатаем пометку и не даём FAIL по частотным
       маркерам; (в) применён к НЕ-авторскому тексту (дев-лог, arXiv, служебка) -> вердикт
       бессмыслен, это не баг скрипта: сначала определи класс текста.
КАК ПОНЯТЬ, ЧТО РАБОТАЕТ: `python vanilla_scan.py --selftest` гоняет два зашитых образца
       (ванильный / живой) и проверяет, что вердикты FAIL и PASS соответственно.
КАК ПОЧИНИТЬ: все пороги и регулярки лежат в словаре MARKERS ниже, по одной строке на
       маркер. Правишь порог - правь и P26-P30 в ~/.claude/skills/taste-check/SKILL.md
       (один источник смысла - там, здесь исполнение).

⚠️ ГРАНИЦА (нашёл Codex T3, 28.07): это ЧАСТОТНЫЙ фильтр, а не судья вкуса. Пороги
   геймятся разбавлением - долить нейтральных слов и «я», и WARN уйдёт, а текст останется
   мёртвым. Поэтому PASS здесь = «грубых робот-маркеров нет», НЕ «написано голосом Антона».
   Голос судит человек и LLM-часть /taste-check по ★ЭТАЛОНУ. Финальный судья = Антон.

⚠️ НЕ судит (замер ОПРОВЕРГ эти «ориентиры», не возвращать): «не X, а Y» - это ЕГО приём
   (он 3.03-5.21, мы 2.93); афоризм в конце абзаца (он 20.0%, мы 17.6%); средняя длина
   предложения (совпадает, 11.4 vs 10.8); длинные тире (P9 отключён Антоном 02.07).
"""
import argparse, io, os, re, sys

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

# имя -> (регулярка, порог, направление, норма Антона, вес)
# направление ">" = плохо когда БОЛЬШЕ порога; "<" = плохо когда МЕНЬШЕ.
MARKERS = {
    "зеркальная «X, а не Y»": (re.compile(r",\s+а\s+не\s+"), 1.0, ">", "0.00", "FAIL"),
    "«это не X, это Y»":      (re.compile(r"[Ээ]то\s+не\s+[^.!?\n]{1,60}[.,]\s*[Ээ]то\s"), 0.01, ">", "0.00", "FAIL"),
    "триада «A, B и C»":      (re.compile(r"\b[\wё]{3,},\s+[\wё]{3,}\s+и\s+[\wё]{3,}\b", re.I | re.U), 1.0, ">", "0.00", "WARN"),
    "лексикон Антона":        (re.compile(r"(?i)(видюх|втор(ой|ая) (мозг|голова)|openclaw|чатжпт|промудохал|спойлер|блин|облажал|стыдно|идиот|туплю|навернул)"), 4.0, "<", "18.21", "FAIL"),
    "первое лицо «я/мне/мой»": (re.compile(r"(?<![\w])(я|мне|меня|мой|моя|моё|мои)(?![\w])", re.I | re.U), 25.0, "<", "50.08", "FAIL"),
}
SHORT_MIN = 30.0   # % предложений <= 5 слов; у Антона 33-50, у нас было 24
HEAD_RX = re.compile(r"^#{1,3}\s", re.M)
MIN_WORDS = 120    # ниже этого частоты шумят (тизер) -> только WARN


def clean(t):
    t = re.sub(r"^---\n.*?\n---\n", "", t, flags=re.S)   # frontmatter
    t = re.sub(r"<!--.*?-->", " ", t, flags=re.S)        # служебные комментарии адаптера
    t = re.sub(r"https?://\S+", " ", t)                  # ссылки/футер не считаем
    return t


def scan(raw):
    t = clean(raw)
    # Заголовки считаем ПОСЛЕ вырезания frontmatter и HTML-комментариев: `## ...` внутри
    # многострочного комментария адаптера - это служебка, а не заголовок в теле поста.
    # (нашёл Codex T3, 28.07: чистый черновик получал ложный FAIL)
    heads = len(HEAD_RX.findall(t))
    t = re.sub(r"^#.*$", "", t, flags=re.M)
    words = len(re.findall(r"[\wё]+", t, re.U))
    k = max(words, 1) / 1000.0
    sents = [s for s in re.split(r"(?<=[.!?])\s+", t) if s.strip()]
    short = 100.0 * sum(1 for s in sents if len(re.findall(r"[\wё]+", s, re.U)) <= 5) / max(len(sents), 1)
    rows, worst = [], 0
    tiny = words < MIN_WORDS
    for name, (rx, thr, direction, norm, weight) in MARKERS.items():
        val = round(len(rx.findall(t)) / k, 2)
        bad = (val > thr) if direction == ">" else (val < thr)
        v = "ok"
        if bad:
            v = "WARN" if (tiny or weight == "WARN") else "FAIL"
            worst = max(worst, 1 if v == "WARN" else 2)
        rows.append((name, val, ("<=%.2f" % thr) if direction == ">" else (">=%.1f" % thr), norm, v))
    v = "ok"
    if short < SHORT_MIN:
        v = "WARN"; worst = max(worst, 1)
    rows.append(("% коротких предл (<=5 сл)", round(short, 1), ">=%.0f" % SHORT_MIN, "33-50", v))
    v = "ok"
    if heads:
        v = "WARN" if tiny else "FAIL"; worst = max(worst, 1 if tiny else 2)
    rows.append(("заголовки ## в теле поста", heads, "0", "0", v))
    return words, rows, worst, tiny


def report(path, raw):
    words, rows, worst, tiny = scan(raw)
    print("🎛 vanilla_scan: %s · %d слов" % (path, words))
    if words == 0 and len(raw.strip()) > 40:
        # текст есть, слов ноль -> почти всегда файл не в UTF-8. Молчать тут = ложная тишина.
        print("   ❗ в файле %d символов, но 0 слов: похоже, кодировка не UTF-8. Перекодируй и прогони снова." % len(raw.strip()))
        return 3
    if tiny:
        print("   ⚠️ короткий текст (<%d слов): частоты шумят, максимум WARN" % MIN_WORDS)
    print("%-27s %9s %9s %9s  %s" % ("МАРКЕР (на 1000 слов)", "текст", "порог", "у Антона", "вердикт"))
    for n, val, thr, norm, v in rows:
        print("%-27s %9s %9s %9s  %s" % (n, val, thr, norm, v))
    verdict = ["✅ PASS", "⚠️ WARN", "❌ FAIL"][worst]
    print("ИТОГ: %s  (принципы P26-P30, скилл /taste-check)" % verdict)
    return worst


